import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const browser = await chromium.launch({ headless: true, channel: 'chrome', args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1536, height: 1024 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
page.on('console', m => { if(m.type()==='error') errors.push(m.text()); });
await page.goto('http://localhost:3010/demo', { waitUntil: 'networkidle', timeout: 120000 });
await page.getByRole('heading', { name: 'Lançamentos do mês' }).waitFor({ timeout: 90000 });
await page.screenshot({ path: 'C:/Projetos/finance-manager/.qa-desktop.png', fullPage: true });
await fs.writeFile('C:/Projetos/finance-manager/.qa-demo-state.json', await page.evaluate(() => localStorage.getItem('conta-clara-demo-v1')));
console.log(JSON.stringify({url:page.url(),title:await page.title(),errors,desktopOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}));
await page.setViewportSize({width:390,height:844});
await page.screenshot({ path:'C:/Projetos/finance-manager/.qa-mobile.png',fullPage:true });
console.log(JSON.stringify({mobileOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}));
await page.getByRole('button',{name:'Abrir menu'}).click();
await page.getByRole('link',{name:'Responsáveis',exact:true}).click();
await page.getByRole('button',{name:'Novo responsável'}).click();
await page.getByRole('dialog').getByLabel('Nome',{exact:true}).fill('Teste QA');
await page.getByRole('button',{name:'Salvar',exact:true}).click();
await page.getByText('Teste QA',{exact:true}).waitFor();
console.log('Responsible creation passed');
await page.setViewportSize({width:1536,height:1024});
await page.getByRole('link',{name:'Visão geral',exact:true}).click();
await page.getByRole('button',{name:'Nova compra',exact:true}).click();
const dialog=page.getByRole('dialog');
await dialog.getByLabel('Estabelecimento',{exact:true}).fill('Compra QA');
await dialog.getByLabel('Valor total (R$)',{exact:true}).fill('1200,00');
await dialog.getByLabel('Número de parcelas',{exact:true}).fill('6');
await dialog.getByLabel('Quem paga esta compra?',{exact:true}).selectOption({label:'Teste QA'});
await dialog.getByRole('button',{name:'Registrar compra',exact:true}).click();
await dialog.waitFor({state:'hidden'});
await page.getByRole('link',{name:'Responsáveis',exact:true}).click();
const row=page.getByRole('row').filter({hasText:'Teste QA'});
await row.getByText('R$ 1.200,00',{exact:true}).first().waitFor();
await row.getByRole('button',{name:'Receber'}).click();
await page.getByRole('dialog').getByLabel('Valor recebido (R$)',{exact:true}).fill('250,00');
await page.getByRole('button',{name:'Registrar recebimento',exact:true}).click();
await page.getByRole('dialog').waitFor({state:'hidden'});
await row.getByText('R$ 950,00',{exact:true}).waitFor();
await page.reload({waitUntil:'networkidle'});
await page.getByRole('row').filter({hasText:'Teste QA'}).getByText('R$ 950,00',{exact:true}).waitFor();
console.log('Purchase -> installments -> partial reimbursement -> reload passed');
const api=await page.request.get('http://localhost:3010/api/finance');
console.log('Unauthenticated API status:',api.status());
await page.goto('http://localhost:3010/dashboard',{waitUntil:'networkidle'});
console.log('Protected route:',page.url());
await page.screenshot({path:'C:/Projetos/finance-manager/.qa-login.png',fullPage:true});
console.log(JSON.stringify({errors}));
await browser.close();
